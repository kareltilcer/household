// The service worker that shows a Web Push (PRD 03 §4, 06-clients §6): the one script of the app
// that runs with no page open. It is a file of its own at the origin's root, written by the build
// (plugin.ts) and so part of the build's id, with nothing of the app's bundle in it.
//
// It does two things: it shows what the server pushed, and when a notification is pressed it has
// the address the notification names opened, by a page of the app that is open or in a new one.
// It handles no `fetch` and keeps no cache, so it serves no file of any build: ADR 0025 refused a
// worker for learning of a newer build because one caches the very files a newer build replaces,
// and this one cannot.

/** Where the worker is served: the origin's root, so that its scope is the whole app. */
export const pushWorkerFile = 'push-worker.js'

/**
 * The `type` of the message the worker posts a page that is open when a notification is pressed:
 * with it, `url`, the address to go to, a path of the app's own origin (src/push/worker.ts).
 */
export const pushOpenMessage = 'household.push.open'

/**
 * The worker's source. What the server sends is `notify.webPushMessage`: a title, a body, the
 * address a press opens, a tag that replaces an earlier notification of the same thing, and the
 * household and the notification it is of. A push that carries nothing readable shows nothing:
 * the words are the server's, in the member's language, and the worker has none of its own.
 */
export function pushWorkerScript(): string {
  return `// Generated by apps/web/build/pushWorker.ts.
self.addEventListener('push', function (event) {
  var sent
  try {
    sent = event.data ? event.data.json() : null
  } catch (_) {
    sent = null
  }
  if (!sent || typeof sent.title !== 'string' || sent.title === '') return
  var options = {
    body: typeof sent.body === 'string' ? sent.body : '',
    data: { url: typeof sent.url === 'string' ? sent.url : '/' },
  }
  if (typeof sent.tag === 'string' && sent.tag !== '') options.tag = sent.tag
  event.waitUntil(self.registration.showNotification(sent.title, options))
})

self.addEventListener('notificationclick', function (event) {
  event.notification.close()
  var target = new URL((event.notification.data && event.notification.data.url) || '/', self.location.origin)
  // An address of another origin is none of the app's: the press opens the app itself.
  if (target.origin !== self.location.origin) target = new URL('/', self.location.origin)
  event.waitUntil(
    self.clients.matchAll({ type: 'window', includeUncontrolled: true }).then(function (open) {
      // A page of the app that is open is told the address, and goes there by its own router;
      // with none open, the address is opened, and the app resolves it as it starts.
      for (var i = 0; i < open.length; i++) {
        if ('focus' in open[i]) {
          open[i].postMessage({ type: ${JSON.stringify(pushOpenMessage)}, url: target.pathname + target.search + target.hash })
          return open[i].focus()
        }
      }
      return self.clients.openWindow(target.href)
    }),
  )
})
`
}
